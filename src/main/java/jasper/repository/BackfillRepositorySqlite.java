package jasper.repository;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.context.annotation.Profile;
import org.springframework.stereotype.Repository;

@Repository
@Profile("sqlite")
public interface BackfillRepositorySqlite extends BackfillRepository {
	Logger logger = LoggerFactory.getLogger(BackfillRepositorySqlite.class);

	@Override
	default int backfillMetadata(String origin, boolean pinned, int batchSize) {
		logger.warn("{} Bulk backfill disabled for SQLite, metadata will be regenerated by background backfill", origin);
		return 0;
	}
}
